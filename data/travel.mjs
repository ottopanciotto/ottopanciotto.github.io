export const travelYears = [
  ...new Set(travelNotes.map((note) => note.start.slice(0, 4))),
]
  .sort()
  .reverse();
export const travelRange = `${travelYears.at(-1)}–${travelYears[0]}`;
export const RECENT_COUNT = 6;

export function selectTravelNotes(year = "all", showAll = false) {
  const matching = travelNotes.filter(
    (note) => year === "all" || note.start.startsWith(`${year}-`),
  );
  return {
    matching,
    visible:
      year === "all" && !showAll ? matching.slice(0, RECENT_COUNT) : matching,
  };
}
